struct HuffmanEncodeEntry {
    typealias Raw = (bits: UInt32, nbits: UInt32)

    private let raw: Raw

    fileprivate init(packed: Raw) {
        self.raw = packed
    }

    var bits: UInt32 {
        self.raw.bits
    }

    var nbits: Int {
        Int(self.raw.nbits)
    }
}

